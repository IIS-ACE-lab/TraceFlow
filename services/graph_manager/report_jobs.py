# services/graph_manager/report_jobs.py
"""
A project's per-configuration graph jobs, written from its run registry (TODO.md §29): the graphs of the P2
Model Performance Report (paper/draft_6 Figs. 8.i, 8.ii) as graph jobs, so the released graph_config.yaml and
the panel (FIGURES → Draw) redraw them at full size.

    python -m services.graph_manager.report_jobs jobs   --project ZvW [--code-readings]
    python -m services.graph_manager.report_jobs facets --project ZvW

A configuration is a data entry, a model and its figure queue (a run two queues share is its figure queue's,
not the S3 queue's); its runs are its trainings (Wouters' ten splits, or Zaid's one). Each gets three jobs, the
report's columns, and `facets` lays them side by side, one facet per configuration:

    loss        training and validation loss per epoch (training_objective, validation_objective), the
                trainings pooled (groups: mean, +-1 SD band, no curve per training, as Figs. 8.i, 8.ii)
    ge          the test's mean rank over the attacks (mean_attack_rank_curve, the latest All test), the
                trainings pooled (groups: mean, +-1 SD band, no curve per training), the geometric mean and
                the median over the attacks, each training's N̄tGE and their median, the N_val and N_budget lines (overlays)
    confidence  each training's key confidence (key_recovery top1_top2_score_margin, strip)

`jobs` keeps job 0 (the model judge's) and rewrites every other job; `facets` rewrites the faceting list from
the figures the jobs drew (draw the jobs first: make graph GRAPH_ID=<id>, or the panel). The configurations, their
order and their letters are the report's (dataset I to VI, a, b, ... as in Figs. 8.i, 8.ii). A code reading (a
`*_code` queue, `w_fig2_ascad_n100_linear`) is not a P2 result and is left out unless --code-readings.

Author: Shraddha Mishra
"""
from __future__ import annotations

import argparse
import datetime
import json
import re
import string
from pathlib import Path
from typing import Any, Mapping, Optional

import yaml

from services.graph_manager.graph_export import Project

ORDER = ["dpav4", "aes_hd", "aes_rd", "ascad_n0", "ascad_n50", "ascad_n100"]        # the report's dataset order
ROMAN = dict(zip(ORDER, ["I", "II", "III", "IV", "V", "VI"]))
BASE = re.compile(r"(dpav4|aes_hd|aes_rd|ascad_n0|ascad_n50|ascad_n100)")
S3 = {"s3_ascad_n100_zaid": "S3 Z set.", "s3_ascad_n100_wouters": "S3 W set."}
TRAIN, VALID = "#666666", "#00B4D8"          # the report's training and validation colours
# the report's GE (paper/draft_6 p2_report_model_performance.py, theme results): the mean and its band, the geometric
# mean and the median over the attacks, each training's N̄tGE; the bands' alpha (loss: LOSS_BAND)
GE, GE_BAND, GE_GEO, GE_MEDIAN, INK = "#4A148C", "#7E57C2", "#00C853", "#FF00FF", "#222222"
GE_ALPHA, LOSS_ALPHA = .32, .22
GENERATED = "# ── generated by services/graph_manager/report_jobs.py from the run registry ({date}); regenerate, do not edit ──"


def code_reading(queue: str) -> bool:
    """A queue whose setting or network only a released script has: not a P2 result (ZvW README, Code readings)."""
    return queue.endswith("_code") or queue == "w_fig2_ascad_n100_linear"


def _who(queue: str) -> str:
    who = "Z" if queue.startswith("z") else S3.get(queue, "W")
    return who + (" code" if queue.endswith("_code") else (" paper" if who == "Z" else ""))


def _network(model_id: str) -> str:
    return "NoConv1" if "NoConv1" in model_id else ("Zaid lin." if "linear" in model_id else "Zaid")


def configurations(project: Project, *, with_code: bool = False) -> list[dict[str, Any]]:
    """Every configuration of the project's DONE runs, in the report's order, each {dataset, letter, data, model,
    queue, who, network, preprocessing, runs}."""
    groups: dict[tuple, list[str]] = {}
    for entry in project.registry().values():
        if not isinstance(entry, Mapping) or entry.get("status") != "DONE":
            continue
        name = str(entry["model_name"]); snapshot = project.snapshot(name)
        batches = [str(b) for b in entry.get("batches") or []]
        queue = next((b for b in batches if b not in S3), batches[0] if batches else "?")
        if code_reading(queue) and not with_code:
            continue
        groups.setdefault((snapshot["data"]["name"], str(entry["model_id"]), queue), []).append(name)
    out = []
    for (data, model, queue), runs in groups.items():
        base = BASE.match(data).group(1)
        out.append(dict(dataset=base, data=data, model=model, queue=queue, who=_who(queue), network=_network(model),
                        preprocessing=data[len(base) + 1:].removesuffix("_w"), runs=sorted(runs)))
    out.sort(key=lambda c: (ORDER.index(c["dataset"]), c["who"] != "Z paper", c["who"] != "Z code",
                            c["who"].startswith("S3"), c["preprocessing"], c["network"]))
    for base in ORDER:
        for i, c in enumerate(c for c in out if c["dataset"] == base):
            c["letter"] = string.ascii_lowercase[i]
    return out


def _tag(c: Mapping[str, Any]) -> str:
    return f"{ROMAN[c['dataset']]}{c['letter']}"


def _label(c: Mapping[str, Any]) -> str:
    return f"{ROMAN[c['dataset']]}.{c['letter']} {c['who']} · {c['network']} · {c['preprocessing']}"


def jobs_for(c: Mapping[str, Any], first_id: int) -> list[dict[str, Any]]:
    """The configuration's three jobs: loss, ge, confidence."""
    runs = list(c["runs"]); tag = _tag(c); several = len(runs) > 1
    group = [{"label": _label(c), "models": runs, "band": "std"}] if several else None
    pooled = f", mean of {len(runs)} ± 1 SD" if several else ""
    # folder: project: a configuration of one training draws into graphs/jobs/ too, where git keeps it (its run's
    # artifacts it does not), so the paper's link to each graph opens that graph alone
    common = {"type": "model_overlay", "enabled": True, "models": runs, "folder": "project", "export": {"formats": ["svg"]}}
    loss = {
        "id": first_id, "name": f"p2_{tag}_loss", **common, "source": "attack_metrics", "mode": "auto",
        "metric": ["training_objective", "validation_objective"], "metric_process": {"training_objective": "train"},
        "processes": ["validation"], "plot_type": "line", "output_file_name": f"p2_{tag}_loss",
        "style": {"series": {**{f"{r}:training_objective": {"color": TRAIN} for r in runs},
                             **{f"{r}:validation_objective": {"color": VALID} for r in runs}},
                  "line": {"marker": "none"}, "std_band": {"alpha": LOSS_ALPHA},
                  "text_rules": [{"target": "title", "text": f"{_label(c)}: loss"},
                                 {"target": "y_label", "text": "cross-entropy loss"}]},
        "legend": {"enabled": True, "mode": "custom", "entries": [{"label": f"training{pooled}", "color": TRAIN},
                                                                  {"label": f"validation{pooled}", "color": VALID}]},
    }
    ge = {
        "id": first_id + 1, "name": f"p2_{tag}_ge", **common, "source": "attack_metrics", "mode": "auto",
        "metric": "mean_attack_rank_curve", "processes": ["test"], "test": "latest", "plot_type": "line",
        "output_file_name": f"p2_{tag}_ge", "overlays": {"ge_averages": ["geometric", "median"], "ntge": True,
                                                         "trace_lines": ["n_val", "budget"],
                                                         "colors": {"geometric": GE_GEO, "median": GE_MEDIAN, "ntge": INK}},
        # a marker at each of the test's trace counts hides the averages
        # the legend under the axes (inside, its eight entries cover the curves or the N̄tGE marks at rank 1 of some
        # configuration), the figure 3.72 in tall so that with it the graph is as tall as the loss and the key
        # confidence (4.8 in): a facet row of equal heights keeps the three graphs' text one size
        "style": {"line": {"marker": "none"}, "figure": {"height": 3.72}, "std_band": {"alpha": GE_ALPHA},
                  "series": {r: {"color": GE} for r in runs},
                  "text_rules": [{"target": "title", "text": f"{_label(c)}: guessing entropy"}]},
        "legend": {"enabled": True, "position": "below", "columns": 2},
    }
    confidence = {
        "id": first_id + 2, "name": f"p2_{tag}_confidence", **common, "source": "key_recovery", "mode": "auto",
        "metric": "top1_top2_score_margin", "processes": ["test"], "plot_type": "strip",
        "output_file_name": f"p2_{tag}_confidence", "style": {   # the default height: a facet row of equal heights keeps the three graphs' text one size
                                                        "text_rules": [{"target": "title", "text": f"{_label(c)}: key confidence"}]},
    }
    if group:
        # the report's loss and GE (Figs. 8.i, 8.ii): the mean and its band only, no curve per training
        loss["groups"] = [{**group[0], "members": False}]
        ge["groups"] = [{**group[0], "members": False, "color": GE, "band_color": GE_BAND}]
        confidence["groups"] = group
    return [loss, ge, confidence]


def _split(text: str) -> tuple[str, str, str]:
    """(everything before job 1, job 0's block and the rest of jobs, the faceting section)."""
    jobs = text.index("\njobs:\n")
    facets = text.index("\nfaceting:")
    return text[:jobs + 1], text[jobs + 1:facets + 1], text[facets + 1:]


def _job0(jobs_section: str) -> str:
    """The jobs: line and job 0's block, as written (comments included)."""
    m = re.search(r"\n  - id: 1\b", jobs_section)
    return jobs_section[:m.start() + 1] if m else jobs_section


def _dump(items: list[dict[str, Any]]) -> str:
    text = yaml.safe_dump(items, sort_keys=False, allow_unicode=True, width=120, default_flow_style=None)
    return "".join("  " + line if line.strip() else line for line in text.splitlines(keepends=True))


def write_jobs(project: Project, *, with_code: bool = False) -> dict[str, Any]:
    """Rewrite every job but job 0 of the project's graph_config.yaml from its configurations."""
    path = project.graph_config
    text = path.read_text(encoding="utf-8")
    head, jobs_section, facets = _split(text)
    configs = configurations(project, with_code=with_code)
    jobs = [job for i, c in enumerate(configs) for job in jobs_for(c, 1 + 3 * i)]
    stamp = GENERATED.format(date=datetime.date.today().isoformat())
    body = (_job0(jobs_section).rstrip("\n") + "\n\n  " + stamp + "\n" + _dump(jobs) + "\n")
    path.write_text(head + body + facets, encoding="utf-8")
    return {"configurations": len(configs), "jobs": len(jobs), "ids": [1, len(jobs)], "path": str(path)}


def _drawn(project: Project, job: Mapping[str, Any]) -> Optional[str]:
    """The svg the job drew, as a facet address (relative to <project>/graphs/, or artifacts/... into a run's)."""
    from services.graph_manager.graph_manager import GraphManager

    folder = GraphManager(project_name=project.name).job_output_dir(job)
    found = sorted(Path(folder).rglob("*.svg"))
    if not found:
        return None
    graphs = project.graphs
    try:
        return found[0].relative_to(graphs).as_posix()
    except ValueError:
        return found[0].relative_to(project.root).as_posix()


def write_facets(project: Project) -> dict[str, Any]:
    """Rewrite the faceting list: one facet per configuration, its loss, ge and confidence figures side by side."""
    path = project.graph_config
    text = path.read_text(encoding="utf-8")
    head, jobs_section, _facets = _split(text)
    jobs = {int(j["id"]): j for j in (yaml.safe_load(text).get("jobs") or []) if int(j.get("id", 0)) > 0}
    facets, missing = [], []
    for first in range(1, max(jobs, default=0) + 1, 3):
        trio = [jobs.get(first + k) for k in range(3)]
        if not all(trio):
            continue
        addresses = [_drawn(project, job) for job in trio]
        if not all(addresses):
            missing += [job["id"] for job, a in zip(trio, addresses) if not a]
            continue
        tag = trio[0]["name"].removeprefix("p2_").removesuffix("_loss")
        facets.append({"id": len(facets) + 1, "name": f"p2_{tag}", "enabled": True, "output_file_name": f"p2_{tag}",
                       "panels": [{"file_id": k + 1, "address": a} for k, a in enumerate(addresses)],
                       "arrangement": {"mode": "horizontal", "order": [1, 2, 3]},
                       "legend": {"enabled": False}, "export": {"formats": ["svg"]}})
    stamp = GENERATED.format(date=datetime.date.today().isoformat())
    path.write_text(head + jobs_section + "faceting:\n\n  " + stamp + "\n" + _dump(facets), encoding="utf-8")
    return {"facets": len(facets), "jobs not drawn yet": missing, "path": str(path)}


def main(argv: Optional[list[str]] = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("what", choices=["jobs", "facets"])
    ap.add_argument("--project", required=True)
    ap.add_argument("--code-readings", action="store_true", help="also the code readings (not P2 results)")
    args = ap.parse_args(argv)
    project = Project(args.project)
    out = write_jobs(project, with_code=args.code_readings) if args.what == "jobs" else write_facets(project)
    print(json.dumps(out))


if __name__ == "__main__":
    main()
